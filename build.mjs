import { readFileSync, writeFileSync, mkdirSync, cpSync } from "node:fs";
import { Script } from "node:vm";
import { dirname } from 'node:path';
import { runtimeFiles } from './scripts/runtime-files.mjs';
const sources = [
  "src/password.js",
  "src/settings.js",
  "src/threat-model.js",
  "src/wordlist.js",
  "src/main.js",
];
const code = sources
  .map((path) =>
    readFileSync(path, "utf8")
      .replace(/^import\s[\s\S]*?;\r?\n/gm, "")
      .replace(/^export /gm, ""),
  )
  .join("\n");
const bundle = `// Generated by npm run build.\n(()=>{\n${code}\n})();\n`;
new Script(bundle, { filename: "src/app.js" });
writeFileSync("src/app.js", bundle);
for (const path of runtimeFiles) {
  mkdirSync(dirname(`dist/${path}`), { recursive: true });
  cpSync(path, `dist/${path}`);
}
console.log("NYQVRA built: dist/ (no runtime dependencies)");
