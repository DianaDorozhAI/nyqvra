'use strict';
const { app, clipboard } = require('electron');
const assert = require('node:assert/strict');
const { createWindow } = require('./main.cjs');
const path = require('node:path');
const fs = require('node:fs');
fs.mkdirSync(path.resolve(__dirname, '../work'), { recursive: true });
app.setPath('userData', fs.mkdtempSync(path.resolve(__dirname, '../work/desktop-smoke-')));
const timer = setTimeout(() => { console.error('Desktop smoke timed out'); app.exit(1); }, 30000);
app.whenReady().then(async () => {
  const win = await createWindow({ show: false });
  console.log('Desktop page loaded');
  const result = await win.webContents.executeJavaScript(`(async () => {
    const q = s => document.querySelector(s);
    const initial = q('#password').value;
    q('#generate').click();
    const generated = q('#password').value;
    q('[data-lang="en"]').click();
    const english = document.documentElement.lang;
    q('[data-lang="ru"]').click();
    const russian = document.documentElement.lang;
    const assets = [...document.images].every(image => image.complete && image.naturalWidth > 0);
    const isolation = typeof window.require === 'undefined' && typeof window.process === 'undefined';
    const remoteBlocked = await fetch('https://example.com').then(() => false, () => true);
    return { initialLength: initial.length, generatedLength: generated.length, changed: initial !== generated, english, russian, assets, isolation, remoteBlocked };
  })()`);
  assert.equal(result.initialLength, 24); assert.equal(result.generatedLength, 24);
  assert.equal(result.changed, true); assert.equal(result.english, 'en'); assert.equal(result.russian, 'ru');
  assert.equal(result.assets, true); assert.equal(result.isolation, true);
  assert.equal((await win.webContents.session.fetch('nyqvra://app/package.json')).status, 404);
  assert.equal(result.remoteBlocked, true);
  console.log('Isolation, generation, assets and RU/EN passed');
  const savedFromUI = await win.webContents.executeJavaScript(`(async () => {
    const q = s => document.querySelector(s);
    const expected = q('#password').value;
    const hide = q('.result-actions button:not(#copy):not(#desktop-save)');
    if (!hide) throw new Error('Hide control missing');
    hide.click();
    q('#desktop-save').click();
    const form = q('.journal-save form');
    form.elements.label.value = 'UI save test only';
    form.requestSubmit();
    for (let attempt = 0; attempt < 100 && q('.journal-save').open; attempt++) await new Promise(resolve => setTimeout(resolve, 30));
    if (q('.journal-save').open) throw new Error('Save dialog did not close');
    const entries = await window.nyqvraDesktop.list();
    const entry = entries.find(item => item.label === 'UI save test only');
    if (!entry) throw new Error('UI entry missing');
    const correct = await window.nyqvraDesktop.reveal(entry.id) === expected;
    q('.journal-tab').click();
    for (let attempt = 0; attempt < 100 && !q('.journal-entry'); attempt++) await new Promise(resolve => setTimeout(resolve, 30));
    const masked = q('.journal-secret')?.textContent === '••••••••••••';
    q('.journal-back').click();
    await window.nyqvraDesktop.remove(entry.id);
    return { correct, masked, dialogClosed: !q('.journal-save').open };
  })()`);
  assert.deepEqual(savedFromUI, { correct: true, masked: true, dialogClosed: true });
  console.log('Masked generator → save dialog → journal UI passed');
  const journal = await win.webContents.executeJavaScript(`(async () => {
    const api = window.nyqvraDesktop;
    const item = await api.save({ label: 'Desktop smoke account', url: 'https://example.com', secret: 'NYQVRA-journal-test-only' });
    const list = await api.list();
    const revealed = await api.reveal(item.id);
    return { id: item.id, hidden: !('secret' in list[0]), correct: revealed === 'NYQVRA-journal-test-only', button: !!document.querySelector('#desktop-save') };
  })()`);
  assert.equal(journal.hidden, true); assert.equal(journal.correct, true); assert.equal(journal.button, true);
  console.log('Encrypted journal save/list/reveal passed');
  assert.equal(fs.readFileSync(path.join(app.getPath('userData'), 'journal.enc')).includes(Buffer.from('NYQVRA-journal-test-only')), false);
  await win.webContents.executeJavaScript(`window.nyqvraDesktop.copy(${JSON.stringify(journal.id)})`);
  assert.equal(await clipboard.readText(), 'NYQVRA-journal-test-only');
  await win.webContents.executeJavaScript(`window.nyqvraDesktop.remove(${JSON.stringify(journal.id)})`);
  console.log('Journal copy/delete passed');
  // A known test marker only; never read the user's existing clipboard.
  await win.webContents.executeJavaScript(`window.nyqvraDesktop.writeText('NYQVRA-desktop-smoke')`);
  assert.equal(await clipboard.readText(), 'NYQVRA-desktop-smoke');
  await clipboard.clear();
  console.log(JSON.stringify({ desktop: 'PASS', ...result }));
  clearTimeout(timer); win.destroy(); app.exit(0);
}).catch(error => { console.error(error?.stack || JSON.stringify(error, Object.getOwnPropertyNames(error || {}))); clearTimeout(timer); app.exit(1); });
